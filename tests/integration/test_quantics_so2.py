#!/usr/bin/env python3
''' Program tests. '''
import os
import unittest
from test_zaghop import QuanticsTest


class QuanticsSo2Test(QuanticsTest):
    """ Trajectory tests using the quantics operator library.

    The restart, dvr and oper files are generated by Quantics from so2.inp (SO2 LVC model with
    spin-orbit coupling, operator mr-cisd.op) and zaghop is run in zagreb_trj/traj."""

    trajdir = os.path.join("zagreb_trj", "traj")
    quantics_input = "so2.inp"

    def test_ldsh_isc(self):
        """ Test locally diabatic FSSH with SOC on SO2 model.

        Locally diabatic propagation does not depend on the ordering of the
        diabatic states, so the diabatic coefficients are also compared to
        check the reordering of the triplet components."""
        self.run_traj()
        self.compare_energy()
        self.compare_results("cstate_diab")
        self.compare_results("prob")


if __name__ == '__main__':
    unittest.main(verbosity=2)
